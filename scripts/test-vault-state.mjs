import assert from 'node:assert/strict';
import {canCollect,thawProgress,emptyVaultRun,restoreVaultRun,createLocalPass,PASS_LIFETIME_MS} from '../src/components/VaultState.ts';
const start=100000;
const run={version:1,startedAt:start,key:null,unlockedAt:null};
assert.equal(canCollect(emptyVaultRun(),start+999999),false);
assert.equal(canCollect(run,start+29999),false);
assert.equal(canCollect(run,start+30000),true);
assert.equal(thawProgress(run,start+15000),.5);
assert.equal(thawProgress(run,start-1),0);
assert.equal(thawProgress(run,start+40000),1);
assert.deepEqual(restoreVaultRun(JSON.stringify(run),start+12000),run);
assert.deepEqual(restoreVaultRun('broken',start),emptyVaultRun());
assert.deepEqual(restoreVaultRun(JSON.stringify(run),start-1),emptyVaultRun());
const key=createLocalPass();assert.match(key,/^SNOWY-FREE-[A-Z2-9]{4}-[A-Z2-9]{4}-\d{4}$/);
const completed={...run,key,unlockedAt:start+30000};
assert.deepEqual(restoreVaultRun(JSON.stringify(completed),start+35000),completed);
assert.deepEqual(restoreVaultRun(JSON.stringify({...completed,unlockedAt:start+10000}),start+35000),emptyVaultRun());
assert.deepEqual(restoreVaultRun(JSON.stringify(completed),start+30000+PASS_LIFETIME_MS+1),emptyVaultRun());
console.log('Passed: exact 30-second boundary, mid-thaw restore, invalid/future storage, pass format and expiry.');
